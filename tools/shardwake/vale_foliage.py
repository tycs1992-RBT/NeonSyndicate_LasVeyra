BROADLEAF = [
    # trunk height, trunk radius, lean (x, z), fork limbs, spread, crown height factor, spray, seed
    dict(height=3.4, radius=.42, lean=(.25, .1), limbs=3, spread=.78, crown=1.0, spray='spray_a', seed=11),
    dict(height=4.4, radius=.36, lean=(-.15, .2), limbs=2, spread=.55, crown=1.25, spray='spray_b', seed=23),
    dict(height=2.8, radius=.40, lean=(.9, .25), limbs=3, spread=.9, crown=.85, spray='spray_a', seed=37),
]


def broadleaf(variant):
    """A broadleaf tree: flared trunk with buttress roots, forking limbs, and leaf sprays clustered at the twigs,
    with gaps between the clusters. Returns (wood palette mesh, leaf cards). Base at the origin, metres."""
    spec = BROADLEAF[variant]
    rng = random.Random(spec['seed'])
    wood = Mesh()
    wood.code = BARK_CODE
    cards = Cards()
    tone = _bark_tone(rng)
    lean = np.array([spec['lean'][0], 0, spec['lean'][1]])
    # Trunk: slightly curved, flared at the root.
    trunk, radii = [], []
    for k in range(7):
        t = k / 6
        p = np.array([0, spec['height'] * t, 0]) + lean * t * t + np.array([math.sin(t * 3 + spec['seed']) * .08, 0, 0])
        trunk.append(p)
        radii.append(spec['radius'] * (1.85 - .85 * min(1, t * 3.5)) * (1 - .22 * t))
    trunk[0] = trunk[0] - np.array([0, .35, 0])
    _tube(wood, trunk, radii, tone, 12)
    # Buttress roots running out and down into the ground.
    for r in range(6):
        a = r * math.tau / 6 + rng.uniform(-.3, .3)
        reach = rng.uniform(1.1, 2.0)
        d = np.array([math.cos(a), 0, math.sin(a)])
        pts = [np.array([0, .55, 0]) + d * .15, d * (spec['radius'] * 1.2) + np.array([0, .22, 0]),
               d * (reach * .55) + np.array([0, .04, 0]), d * reach + np.array([0, -.22, 0])]
        _tube(wood, pts, [spec['radius'] * .55, spec['radius'] * .38, .09, .03], tone, 6)
    # Limbs: recursive forks with upward tropism; leaf clusters at the twig ends.
    top = trunk[-1]
    up_dir = (trunk[-1] - trunk[-2]) / np.linalg.norm(trunk[-1] - trunk[-2])
    centre = top + np.array([0, 2.4 * spec['crown'], 0])
    tips = []

    def limb(start, direction, length, radius, depth):
        pts, rad = [start], [radius]
        d = direction / np.linalg.norm(direction)
        p = start
        for s in range(3):
            d = d + np.array([rng.uniform(-.25, .25), .18 + .1 * depth, rng.uniform(-.25, .25)])
            d /= np.linalg.norm(d)
            p = p + d * length / 3
            pts.append(p)
            rad.append(radius * (1 - .25 * (s + 1) / 3))
        _tube(wood, pts, rad, tone, 7 if depth < 2 else 5)
        if depth >= 3 or radius < .05:
            tips.append((p, d))
            return
        n = 2 if depth else spec['limbs']
        for c in range(n):
            a = c * math.tau / n + rng.uniform(-.6, .6)
            side = np.cross(d, [0, 1, 0])
            if np.linalg.norm(side) < 1e-3:
                side = np.array([1., 0, 0])
            side /= np.linalg.norm(side)
            other = np.cross(d, side)
            bend = spec['spread'] * rng.uniform(.75, 1.15)
            nd = d * math.cos(bend) + (side * math.cos(a) + other * math.sin(a)) * math.sin(bend)
            limb(p, nd, length * rng.uniform(.62, .78), radius * .68, depth + 1)
            if depth >= 1 and rng.random() < .55:
                tips.append((p + d * .05, nd))

    for c in range(spec['limbs']):
        a = c * math.tau / spec['limbs'] + rng.uniform(-.3, .3) + spec['seed']
        d = up_dir * math.cos(spec['spread'] * .8) + np.array([math.cos(a), 0, math.sin(a)]) * math.sin(spec['spread'] * .8)
        limb(top - up_dir * .1, d, 2.2 * spec['crown'], spec['radius'] * .62, 0)
    # Leaf sprays: overlapping cards around each twig end, pointing outward, lower and inner ones darker.
    lo = min(p[1] for p, _ in tips)
    hi = max(p[1] for p, _ in tips)
    for p, d in tips:
        cluster = rng.randint(9, 14)
        for k in range(cluster):
            off = np.array([rng.gauss(0, .5), rng.gauss(0, .36), rng.gauss(0, .5)])
            base = p + off
            out = base - centre
            out[1] *= .5
            out /= max(np.linalg.norm(out), 1e-9)
            up = out * .7 + d * .3 + np.array([0, .25, 0]) + np.array([rng.uniform(-.3, .3) for _ in range(3)])
            facing = np.cross(up, np.array([rng.uniform(-1, 1), rng.uniform(-.2, .4), rng.uniform(-1, 1)]))
            if np.linalg.norm(facing) < 1e-3:
                continue
            h = (p[1] - lo) / max(hi - lo, 1e-3)
            inner = np.linalg.norm((p - centre) * [1, .5, 1]) / 3.2
            shade = .62 + .26 * h + .18 * min(1, inner) + rng.uniform(-.06, .06)
            hue = rng.uniform(-.06, .06)
            tint = (min(255, 255 * shade * (1 + hue)), min(255, 255 * shade), min(255, 255 * shade * (1 - hue * 1.5)))
            size = rng.uniform(1.35, 1.95)
            _card(cards, base - up / np.linalg.norm(up) * size * .25, facing, up, size, size, spec['spray'],
                  centre - np.array([0, .8, 0]), tint, 1, rng)
    return wood, cards


# ------------------------------------------------------------------------------------------------ conifers
CONIFERS = [
    dict(height=11.5, radius=.32, whorls=13, reach=2.9, seed=51),
    dict(height=9.0, radius=.27, whorls=11, reach=2.4, seed=67),
]


def conifer(variant):
    """An irregular conifer: a tapering trunk, drooping whorled branches (some missing), and needle fronds laid
    along each branch. Returns (wood palette mesh, needle cards)."""
    spec = CONIFERS[variant]
    rng = random.Random(spec['seed'])
    wood = Mesh()
    wood.code = BARK_CODE
    cards = Cards()
    tone = _bark_tone(rng)
    H = spec['height']
    trunk = [np.array([rng.uniform(-.05, .05) * k, H * k / 8, rng.uniform(-.05, .05) * k]) for k in range(9)]
    trunk[0] = trunk[0] - np.array([0, .3, 0])
    _tube(wood, trunk, [spec['radius'] * (1.6 if k == 0 else 1.15 if k == 1 else (1 - k / 8.4)) for k in range(9)], tone, 10)
    for r in range(5):
        a = r * math.tau / 5 + rng.uniform(-.3, .3)
        d = np.array([math.cos(a), 0, math.sin(a)])
        pts = [np.array([0, .4, 0]) + d * .1, d * .5 + np.array([0, .12, 0]), d * rng.uniform(.9, 1.3) + np.array([0, -.15, 0])]
        _tube(wood, pts, [spec['radius'] * .55, .1, .03], tone, 6)
    for w in range(spec['whorls']):
        t = .16 + .8 * w / (spec['whorls'] - 1)
        y = H * t
        reach = spec['reach'] * (1 - t) ** .85 * rng.uniform(.8, 1.15) + .35
        count = rng.randint(4, 6)
        for b in range(count):
            if rng.random() < .18 and t < .85:
                continue  # missing branches leave gaps through the crown
            a = b * math.tau / count + w * .7 + rng.uniform(-.3, .3)
            d = np.array([math.cos(a), 0, math.sin(a)])
            start = np.array([trunk[0][0], y, trunk[0][2]])
            droop = rng.uniform(.18, .38)
            pts = [start, start + d * reach * .5 + np.array([0, .05, 0]), start + d * reach + np.array([0, -droop, 0])]
            _tube(wood, pts, [.07 * (1 - t) + .02, .04, .015], tone, 5)
            shade = .58 + .38 * t + rng.uniform(-.05, .05)
            tint = (225 * shade, 255 * shade, 235 * shade)
            for k in range(5):
                s = .12 + .22 * k
                base = start + d * reach * s + np.array([0, -droop * s * s, 0])
                size = 1.7 * (1 - .16 * k) * (reach / spec['reach'] + .45)
                up = d + np.array([0, -.15, 0]) + np.cross(d, [0, 1, 0]) * rng.uniform(-.35, .35)
                for twist in (-1, 0, 1):
                    facing = np.array([0, 1., 0]) + np.cross(d, [0, 1, 0]) * .6 * twist
                    _card(cards, base, facing, up, size * .85, size, 'needles',
                          np.array([0, y - .6, 0]), tint, t, rng)
    # A leader at the top.
    tip = trunk[-1]
    for twist in (-1, 1):
        _card(cards, tip - np.array([0, .9, 0]), np.array([twist, 0, .3]), np.array([0, 1., 0]), .9, 1.6, 'needles',
              tip - np.array([0, 1.4, 0]), (240, 255, 240), 1, rng)
    return wood, cards


# ------------------------------------------------------------------------------------------------ ground cover
def ground_cover(spots, seed, flowers=.12, ferns=.15):
    """Irregular grass groups (with occasional flowers and ferns) at (x, z, radius, count) spots, sitting on the
    terrain. Each clump is two crossed cards."""
    rng = random.Random(seed)
    cards = Cards()
    for x, z, radius, count in spots:
        for k in range(count):
            r = radius * math.sqrt(rng.random())
            a = rng.random() * math.tau
            px, pz = x + math.cos(a) * r, z + math.sin(a) * r
            y = land.surface(px, pz) - .03
            roll = rng.random()
            region = 'flowers' if roll < flowers else 'fern' if roll < flowers + ferns else 'grass'
            h = rng.uniform(.35, .7) if region == 'grass' else rng.uniform(.3, .5) if region == 'flowers' else rng.uniform(.45, .7)
            w = h * rng.uniform(1.0, 1.4)
            g = rng.uniform(.82, 1.08)
            tint = (255 * g, 255 * g * rng.uniform(.95, 1.03), 230 * g)
            base = np.array([px, y, pz])
            spin = rng.random() * math.pi
            for c in range(2):
                f = np.array([math.cos(spin + c * math.pi / 2), 0, math.sin(spin + c * math.pi / 2)])
                _card(cards, base, f, np.array([rng.uniform(-.12, .12), 1., rng.uniform(-.12, .12)]), w, h, region,
                      base - np.array([0, 1.2, 0]), tint, .6, rng)
    return cards


def _trail_distance(x, z, trail):
    best = 1e9
    for (ax, az), (bx, bz) in zip(trail, trail[1:]):
        dx, dz = bx - ax, bz - az
        t = max(0., min(1., ((x - ax) * dx + (z - az) * dz) / max(dx * dx + dz * dz, 1e-9)))
        best = min(best, math.hypot(x - ax - dx * t, z - az - dz * t))
    return best


def meadow_spots(edge_tufts, near_trail, far_trail, clear=2.05):
    """Irregular ground-cover groups: around Dante's doorway and the first steps of the path, in the meadow the
    spawn camera crosses, beside the far trail, and the path-edge tufts. Anything that would sit on the walking line
    is dropped, so the route stays readable."""
    rng = random.Random(5521)
    spots = []
    # Doorway and first steps: many small groups with gaps between them.
    for k in range(150):
        x, z = rng.uniform(-18, 0), rng.uniform(-16, 5)
        spots.append((x, z, rng.uniform(.5, 1.4), rng.randrange(4, 11)))
    # Open meadow either side of the spawn view, sparser further out.
    for k in range(260):
        x, z = rng.uniform(-30, 26), rng.uniform(-16, 30)
        spots.append((x, z, rng.uniform(.8, 2.1), rng.randrange(5, 14)))
    # Far bank toward the Crown.
    for k in range(40):
        x, z = rng.uniform(-25, 25), rng.uniform(55, 100)
        spots.append((x, z, rng.uniform(.8, 1.8), rng.randrange(4, 10)))
    keep = []
    for x, z, r, n in spots:
        if min(_trail_distance(x, z, near_trail), _trail_distance(x, z, far_trail)) < clear + r * .5:
            continue
        # Stay off the workshop floor, the bridge approach and the ravine.
        if -21 < x < -11 and -1 < z < 9:
            continue
        if 26 < z < 54:
            continue
        keep.append((x, z, r, n))
    # The path-edge tufts sit on the verge on purpose (they soften the paving edge); only drop ones on the line.
    keep += [t for t in edge_tufts if min(_trail_distance(t[0], t[1], near_trail), _trail_distance(t[0], t[1], far_trail)) > 1.45]
    return keep
