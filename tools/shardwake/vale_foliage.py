"""Foliage for the Vale: a painted leaf, needle, grass and flower atlas, and the trees and ground cover built from it.

Everything here is original and generated by this script (CC0, like the rest of the pilot). The atlas is one RGBA
texture; every card carries UVs into one of its regions and is drawn by ValeFoliage.shader (alpha cutout, double
sided, soft wrapped light, sunlit translucency, sun shadows). Trunks and roots are ordinary palette meshes with the
bark surface code, so they get the bark grain channel. Never run on scene load or during Play.
"""
import math
import random
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
from assets import ART, ROOT, Mesh, guid, rgb
import land

ATLAS = ART/'Materials/FoliageAtlas.png'
SIZE = 1024
# Regions in UV space (u0, v0, u1, v1); v grows upward like Unity.
REGIONS = {
    'spray_a': (0., .5, .5, 1.),
    'spray_b': (.5, .5, 1., 1.),
    'needles': (0., 0., .5, .5),
    'grass': (.5, 0., .75, .5),
    'flowers': (.75, .25, 1., .5),
    'fern': (.75, 0., 1., .25),
}
BARK_CODE = 225  # palette surface code for wood: bark grain


# ------------------------------------------------------------------------------------------------ the atlas
def _px(region, x, y, scale):
    """Region-local (0..1, 0 bottom) to pixel coordinates on the supersampled canvas."""
    u0, v0, u1, v1 = REGIONS[region]
    return ((u0 + x * (u1 - u0)) * SIZE * scale, (1 - (v0 + y * (v1 - v0))) * SIZE * scale)


def _mix(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def _leaf(draw, mask, region, base, tip, width, color, rng, scale, vein=True):
    """One ovate leaf with a pointed tip, lit on one side of the midrib, with a darker rim and a vein."""
    bx, by = base
    tx, ty = tip
    dx, dy = tx - bx, ty - by
    length = math.hypot(dx, dy)
    ax, ay = dx / length, dy / length
    nx, ny = -ay, ax
    left, right = [], []
    steps = 14
    for k in range(steps + 1):
        t = k / steps
        w = width * math.sin(math.pi * t ** .85) * (1 - .25 * t)
        px, py = bx + dx * t, by + dy * t
        left.append(_px(region, px + nx * w, py + ny * w, scale))
        right.append(_px(region, px - nx * w, py - ny * w, scale))
    mid = [_px(region, bx + dx * t, by + dy * t, scale) for t in (0, 1)]
    light = _mix(color, (236, 246, 170), .22 + rng.random() * .12)
    shade = _mix(color, (18, 40, 26), .28 + rng.random() * .1)
    draw.polygon(left + right[::-1], fill=_mix(color, (20, 40, 25), .38))  # rim
    inner_l = [(_x * .985 + mid[0][0] * .015, _y * .985 + mid[0][1] * .015) for _x, _y in left]
    draw.polygon([mid[0]] + inner_l[1:-1] + [mid[1]], fill=light)
    inner_r = [(_x * .985 + mid[0][0] * .015, _y * .985 + mid[0][1] * .015) for _x, _y in right]
    draw.polygon([mid[0]] + inner_r[1:-1] + [mid[1]], fill=shade)
    if vein:
        draw.line(mid, fill=_mix(color, (210, 225, 150), .45), width=max(1, int(1.6 * scale)))
    mask.polygon(left + right[::-1], fill=255)


def _stem(draw, mask, region, pts, width, color, scale):
    p = [_px(region, x, y, scale) for x, y in pts]
    for a, b in zip(p, p[1:]):
        draw.line([a, b], fill=color, width=max(1, int(width * scale)))
        mask.line([a, b], fill=255, width=max(1, int(width * scale)))


def _spray(draw, mask, region, rng, scale, twigs, leaf_len, leaf_w, palette):
    """A branching twig rising from the bottom centre: side twigs fan out and carry many small alternating leaves,
    so one card reads as a full spray with gaps between leaves. Back leaves are darker, front leaves lighter."""
    placed = []

    def twig(x, y, ang, length, depth):
        pts = [(x, y)]
        for k in range(6):
            ang += rng.uniform(-.12, .12)
            x += math.cos(ang) * length / 6
            y += math.sin(ang) * length / 6
            pts.append((x, y))
        _stem(draw, mask, region, pts, 3.2 - depth * 1.2, (96, 74, 52), scale)
        count = int(length / leaf_len * 3.2)
        for k in range(count):
            t = .1 + .9 * k / max(1, count - 1)
            i = min(5, int(t * 6))
            f = t * 6 - i
            px = pts[i][0] + (pts[i + 1][0] - pts[i][0]) * f
            py = pts[i][1] + (pts[i + 1][1] - pts[i][1]) * f
            side = 1 if k % 2 else -1
            a = ang + side * rng.uniform(.5, 1.0) + rng.uniform(-.15, .15)
            ln = leaf_len * rng.uniform(.75, 1.2) * (1 - .3 * t)
            placed.append((rng.random() * .8 + .2 * depth, (px, py), (px + math.cos(a) * ln, py + math.sin(a) * ln),
                           leaf_w * rng.uniform(.8, 1.2) * (1 - .25 * t)))
        placed.append((1., pts[-1], (pts[-1][0] + math.cos(ang) * leaf_len, pts[-1][1] + math.sin(ang) * leaf_len), leaf_w))
        return pts

    main = twig(.5, 0., math.pi / 2 + rng.uniform(-.1, .1), .82, 0)
    for k in range(twigs):
        t = .18 + .7 * k / max(1, twigs - 1)
        i = min(5, int(t * 6))
        x, y = main[i]
        side = 1 if k % 2 else -1
        twig(x, y, math.pi / 2 + side * rng.uniform(.55, 1.05), .42 * (1 - .45 * t) * rng.uniform(.85, 1.1), 1)
    for depth, base, tip, w in sorted(placed, key=lambda r: r[0]):
        if not (0 < tip[0] < 1 and 0 < tip[1] < 1):
            continue
        color = palette[rng.randrange(len(palette))]
        color = _mix(color, (24, 52, 34), (1 - depth) * .4)
        _leaf(draw, mask, region, base, tip, w, color, rng, scale)


def _needles(draw, mask, region, rng, scale):
    """A drooping conifer frond: a stem with dense needles and side shoots."""
    def frond(x0, y0, ang, length, density, depth):
        pts = []
        x, y = x0, y0
        for k in range(10):
            pts.append((x, y))
            ang += .03 * (1 if depth else -1) + rng.uniform(-.05, .05)
            x += math.cos(ang) * length / 10
            y += math.sin(ang) * length / 10
        _stem(draw, mask, region, pts, 3.2 - depth, (84, 66, 50), scale)
        for k in range(int(density)):
            t = k / density
            i = min(8, int(t * 9))
            px, py = pts[i]
            a = ang + (1 if k % 2 else -1) * rng.uniform(.6, 1.1)
            ln = (.085 - .035 * t) * rng.uniform(.8, 1.2) * (1 - .25 * depth)
            c = _mix((44, 92, 74), (120, 168, 104), rng.random() * .55 * (1 - depth * .4))
            p0 = _px(region, px, py, scale)
            p1 = _px(region, px + math.cos(a) * ln, py + math.sin(a) * ln, scale)
            draw.line([p0, p1], fill=c, width=max(1, int(3.4 * scale)))
            mask.line([p0, p1], fill=255, width=max(1, int(3.4 * scale)))
        return pts
    main = frond(.5, .02, math.pi / 2 + rng.uniform(-.08, .08), .9, 220, 0)
    for k in range(1, 9):
        x, y = main[k]
        for side in (-1, 1):
            frond(x, y, math.pi / 2 + side * rng.uniform(.75, 1.0), .4 * (1 - k / 11), 70, 1)


def _grass(draw, mask, region, rng, scale):
    for k in range(46):
        x0 = .5 + rng.gauss(0, .14)
        h = rng.uniform(.45, .97)
        bend = rng.uniform(-.25, .25)
        w = rng.uniform(.012, .022)
        c0 = _mix((70, 104, 52), (122, 150, 70), rng.random())
        tipc = _mix(c0, (218, 214, 140), .55)
        pts_l, pts_r = [], []
        for s in range(9):
            t = s / 8
            x = x0 + bend * t * t
            y = .01 + h * t
            ww = w * (1 - t)
            pts_l.append(_px(region, x - ww, y, scale))
            pts_r.append(_px(region, x + ww, y, scale))
        poly = pts_l + pts_r[::-1]
        draw.polygon(poly, fill=c0)
        draw.polygon(pts_l[5:] + pts_r[5:][::-1], fill=tipc)
        mask.polygon(poly, fill=255)


def _flowers(draw, mask, region, rng, scale):
    for k in range(9):
        x0 = .5 + rng.gauss(0, .16)
        h = rng.uniform(.35, .9)
        top = (x0 + rng.uniform(-.08, .08), h)
        _stem(draw, mask, region, [(x0, 0), ((x0 + top[0]) / 2, h * .5), top], 2.2, (88, 120, 62), scale)
        petal = [(240, 236, 220), (246, 214, 120), (200, 176, 232), (236, 190, 150)][rng.randrange(4)]
        r = rng.uniform(.035, .055)
        for p in range(6):
            a = p * math.tau / 6 + rng.random() * .3
            cx, cy = top[0] + math.cos(a) * r * .9, top[1] + math.sin(a) * r * .9
            box = [_px(region, cx - r * .6, cy + r * .6, scale), _px(region, cx + r * .6, cy - r * .6, scale)]
            draw.ellipse(box, fill=_mix(petal, (255, 255, 255), rng.random() * .3))
            mask.ellipse(box, fill=255)
        c = [_px(region, top[0] - r * .45, top[1] + r * .45, scale), _px(region, top[0] + r * .45, top[1] - r * .45, scale)]
        draw.ellipse(c, fill=(214, 150, 52))
        mask.ellipse(c, fill=255)


def _fern(draw, mask, region, rng, scale):
    for side in range(5):
        a0 = math.pi / 2 + (side - 2) * .38 + rng.uniform(-.1, .1)
        pts = []
        x, y, a = .5, .02, a0
        for k in range(10):
            pts.append((x, y))
            a -= .07 * (1 if a0 > math.pi / 2 else -1)
            x += math.cos(a) * .085
            y += math.sin(a) * .085
        _stem(draw, mask, region, pts, 2.4, (80, 110, 58), scale)
        for k in range(1, 9):
            px, py = pts[k]
            for s in (-1, 1):
                aa = a0 + s * 1.2
                ln = .07 * (1 - k / 11)
                _leaf(draw, mask, region, (px, py), (px + math.cos(aa) * ln, py + math.sin(aa) * ln), .018,
                      _mix((70, 120, 60), (120, 160, 80), rng.random()), rng, scale, vein=False)


def _dilate(rgb, alpha):
    """Push opaque colours into transparent texels (push-pull), so mipmaps never pull in a dark fringe."""
    a = (alpha > 127).astype(float)
    acc = rgb * a[..., None]
    wsum = a.copy()
    out = rgb.copy()
    filled = a > 0
    for radius in (2, 4, 8, 16, 32, 64):
        blur_c = np.stack([ndimage.uniform_filter(acc[..., i], 2 * radius + 1) for i in range(3)], -1)
        blur_w = ndimage.uniform_filter(wsum, 2 * radius + 1)
        take = (~filled) & (blur_w > 1e-4)
        out[take] = blur_c[take] / blur_w[take, None]
        filled |= take
    out[~filled] = rgb[a > 0].mean(0) if a.any() else 0
    return out


def atlas():
    """Paint the foliage atlas (RGBA, 1024 square) and write its import settings."""
    scale = 2
    canvas = Image.new('RGB', (SIZE * scale, SIZE * scale), (60, 90, 50))
    alpha = Image.new('L', canvas.size, 0)
    draw, mask = ImageDraw.Draw(canvas), ImageDraw.Draw(alpha)
    rng = random.Random(9071)
    spring = [(88, 140, 62), (104, 156, 70), (74, 122, 58), (122, 164, 74), (66, 110, 60)]
    summer = [(64, 112, 58), (78, 128, 62), (96, 140, 66), (56, 98, 56), (110, 150, 72)]
    _spray(draw, mask, 'spray_a', rng, scale, 8, .12, .042, spring)
    _spray(draw, mask, 'spray_b', rng, scale, 10, .095, .036, summer)
    _needles(draw, mask, 'needles', rng, scale)
    _grass(draw, mask, 'grass', rng, scale)
    _flowers(draw, mask, 'flowers', rng, scale)
    _fern(draw, mask, 'fern', rng, scale)
    img = canvas.resize((SIZE, SIZE), Image.LANCZOS)
    a = np.asarray(alpha.resize((SIZE, SIZE), Image.LANCZOS)).astype(float)
    col = np.asarray(img).astype(float)
    # Painterly speckle so large leaves are not flat fills.
    noise = np.random.default_rng(3).normal(size=(SIZE, SIZE))
    noise = ndimage.gaussian_filter(noise, 1.2)
    col *= (1 + .07 * noise)[..., None]
    col = _dilate(np.clip(col, 0, 255), a)
    out = np.dstack([np.clip(col, 0, 255), a]).astype(np.uint8)
    Image.fromarray(out, 'RGBA').save(ATLAS, optimize=True)
    meta = ATLAS.parent/(ATLAS.name + '.meta')
    meta.write_text('fileFormatVersion: 2\nguid: ' + guid(ATLAS) + '\nTextureImporter:\n  externalObjects: {}\n'
                    '  serializedVersion: 13\n  mipmaps:\n    mipMapMode: 0\n    enableMipMap: 1\n    sRGBTexture: 1\n'
                    '    mipMapsPreserveCoverage: 1\n    alphaTestReferenceValue: 0.45\n'
                    '  bumpmap:\n    convertToNormalMap: 0\n    externalNormalMap: 0\n  isReadable: 0\n  textureType: 0\n'
                    '  textureShape: 1\n  maxTextureSize: 1024\n  textureSettings:\n    serializedVersion: 2\n'
                    '    filterMode: 2\n    aniso: 4\n    mipBias: 0\n    wrapU: 1\n    wrapV: 1\n    wrapW: 1\n'
                    '  alphaSource: 1\n  alphaIsTransparency: 1\n  userData: Shardwake Vale foliage atlas\n'
                    '  assetBundleName:\n  assetBundleVariant:\n')
    return ATLAS


# ------------------------------------------------------------------------------------------------ card meshes
class Cards:
    """Foliage cards: per-vertex position, normal, colour (alpha = wind sway weight) and UV."""

    def __init__(self):
        self.v = []
        self.idx = []

    def quad(self, corners, normals, colors, region, flip=False):
        u0, v0, u1, v1 = REGIONS[region]
        uvs = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
        if flip:
            uvs = [(u1, v0), (u0, v0), (u0, v1), (u1, v1)]
        base = len(self.v)
        for p, n, c, uv in zip(corners, normals, colors, uvs):
            self.v.append((tuple(p), tuple(n), tuple(int(x) for x in c), uv))
        self.idx += [base, base + 1, base + 2, base, base + 2, base + 3]

    def save(self, name):
        from assets import save_mesh
        return save_mesh(name, self.v, self.idx, uv=True)


def _card(cards, centre, facing, up, width, height, region, normal_from, tint, sway, rng, flip=None):
    """A leaf card whose bottom edge is at its stem: up spans the card, facing is its plane normal."""
    facing = facing / np.linalg.norm(facing)
    up = up - facing * np.dot(up, facing)
    up /= max(np.linalg.norm(up), 1e-9)
    side = np.cross(up, facing)
    corners = [centre - side * width / 2, centre + side * width / 2,
               centre + side * width / 2 + up * height, centre - side * width / 2 + up * height]
    normals = []
    for p in corners:
        n = p - normal_from
        n = n / max(np.linalg.norm(n), 1e-9)
        normals.append(n)
    colors = [(tint[0], tint[1], tint[2], sway * 255 * (.4 if k < 2 else 1)) for k in range(4)]
    cards.quad(corners, normals, colors, region, rng.random() < .5 if flip is None else flip)


# ------------------------------------------------------------------------------------------------ wood
BARK = ['5c4636', '6a5040', '574233', '73594a']


def _tube(m, pts, radii, tone_fn, sides=8, ring_twist=0.):
    """A tapering tube through points; tone_fn(k, i) picks the bark tone per segment and side."""
    pts = [np.asarray(p, float) for p in pts]
    frames = []
    prev_side = None
    for k, p in enumerate(pts):
        d = (pts[min(k + 1, len(pts) - 1)] - pts[max(k - 1, 0)])
        d /= max(np.linalg.norm(d), 1e-9)
        ref = np.array([0, 0, 1.]) if abs(d[2]) < .9 else np.array([1., 0, 0])
        side = np.cross(d, ref) if prev_side is None else prev_side - d * np.dot(prev_side, d)
        side /= max(np.linalg.norm(side), 1e-9)
        prev_side = side
        frames.append((p, d, side, np.cross(d, side)))
    rings = []
    for k, (p, d, s, t) in enumerate(frames):
        ring = []
        for i in range(sides):
            a = i * math.tau / sides + ring_twist * k
            ring.append(p + (s * math.cos(a) + t * math.sin(a)) * radii[k])
        rings.append(ring)
    for k in range(len(rings) - 1):
        for i in range(sides):
            j = (i + 1) % sides
            a, b, c, e = rings[k][i], rings[k][j], rings[k + 1][j], rings[k + 1][i]
            out = (a + b) / 2 - frames[k][0]
            m.quad(a, b, c, e, tone_fn(k, i), out)
    return rings


def _bark_tone(rng):
    def pick(k, i):
        return BARK[(k * 3 + i * 7 + rng.randrange(2)) % len(BARK)]
    return pick


